// Command schemagen regenerates db/schema/schema.sql from the Goose
// migrations: it applies every migration to an in-memory SQLite
// database and dumps the resulting DDL.
//
// The migrations are the single source of truth; the schema file is a
// derived artifact consumed by sqlc at build time. It is not versioned:
// run `earthly +generate` (or `go run ./cmd/schemagen`) after changing
// a migration.
package main

import (
	"context"
	"database/sql"
	"flag"
	"fmt"
	"log/slog"
	"os"
	"strings"

	_ "modernc.org/sqlite"

	"librevita.org/internal/core/database"
)

func main() {
	out := flag.String("out", "db/schema/schema.sql", "output schema file")
	flag.Parse()

	db, err := sql.Open("sqlite", "file:schemagen?mode=memory&cache=shared")
	if err != nil {
		fatal("open sqlite: %v", err)
	}
	db.SetMaxOpenConns(1)
	defer db.Close()

	if err := database.Migrate(context.Background(), db, slog.New(slog.DiscardHandler)); err != nil {
		fatal("apply migrations: %v", err)
	}

	rows, err := db.Query(`SELECT type, name, sql FROM sqlite_master
		WHERE sql IS NOT NULL ORDER BY rowid`)
	if err != nil {
		fatal("read sqlite_master: %v", err)
	}
	defer rows.Close()

	var b strings.Builder
	b.WriteString("-- Generated by schemagen from db/migrations (Goose); do not edit.\n")
	b.WriteString("-- Source of truth: the migrations under db/migrations. sqlc consumes\n")
	b.WriteString("-- this consolidated state at build time; regenerate with\n")
	b.WriteString("-- `earthly +generate` after changing a migration.\n\n")

	seen := make(map[string]bool)
	for rows.Next() {
		var typ, name, sqlText string
		if err := rows.Scan(&typ, &name, &sqlText); err != nil {
			fatal("scan sqlite_master: %v", err)
		}
		// Skip Goose bookkeeping: its version table and the sequence
		// helper it creates are runtime state, not domain schema.
		if name == "goose_db_version" || name == "sqlite_sequence" {
			continue
		}
		if seen[name] {
			continue
		}
		seen[name] = true
		fmt.Fprintf(&b, "-- %s: %s\n%s;\n\n", strings.Title(typ), name, strings.TrimRight(sqlText, " \n\t;"))
	}
	if err := rows.Err(); err != nil {
		fatal("iterate sqlite_master: %v", err)
	}

	if err := os.MkdirAll(dirOf(*out), 0o750); err != nil {
		fatal("create output dir: %v", err)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o640); err != nil {
		fatal("write %s: %v", *out, err)
	}
	fmt.Printf("schema written to %s\n", *out)
}

func dirOf(path string) string {
	i := strings.LastIndexByte(path, '/')
	if i < 0 {
		return "."
	}
	return path[:i]
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "schemagen: "+format+"\n", args...)
	os.Exit(1)
}
