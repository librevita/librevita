//go:build ignore

package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
	"text/template"
)

func main() {
	typesPath := flag.String("types", "types.go", "ident defined types")
	outPath := flag.String("out", "codec_gen.go", "generated codecs")
	flag.Parse()
	if err := generate(*typesPath, *outPath); err != nil {
		fmt.Fprintf(os.Stderr, "ident: generate codecs: %v\n", err)
		os.Exit(1)
	}
}

type identType struct {
	Name string
	Stem string
}

const codecTmpl = `// Code generated by go run gen.go; DO NOT EDIT.

package ident

import (
	"database/sql/driver"

	"github.com/google/uuid"
)
{{range .}}
func (id {{.Name}}) UUID() uuid.UUID { return asUUID(id) }
func (id {{.Name}}) String() string { return asUUID(id).String() }
func (id {{.Name}}) IsZero() bool { return asUUID(id) == uuid.Nil }
func (id {{.Name}}) Value() (driver.Value, error) { return valueID(id) }
func (id *{{.Name}}) Scan(src any) error { return scanID(id, src) }
func (id {{.Name}}) MarshalText() ([]byte, error) { return marshalTextID(id) }
func (id *{{.Name}}) UnmarshalText(data []byte) error { return unmarshalTextID(id, data) }
func Parse{{.Stem}}(s string) ({{.Name}}, error) { return Parse[{{.Name}}](s) }
func MustParse{{.Stem}}(s string) {{.Name}} { return MustParse[{{.Name}}](s) }
{{end}}
`

func generate(typesPath, outPath string) error {
	types, err := identTypes(typesPath)
	if err != nil {
		return err
	}
	if len(types) == 0 {
		return fmt.Errorf("%s: no uuid.UUID defined types", typesPath)
	}

	tmpl, err := template.New("codec").Parse(codecTmpl)
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, types); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0o644)
}

func identTypes(path string) ([]identType, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}

	var types []identType
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				return nil, fmt.Errorf("%s: unsupported type spec", path)
			}
			name := ts.Name.Name
			if ts.Assign != 0 {
				return nil, fmt.Errorf("%s: must be a defined type, not an alias", name)
			}
			if !isUUIDType(ts.Type) {
				return nil, fmt.Errorf("%s: must be defined as uuid.UUID", name)
			}
			stem := strings.TrimSuffix(name, "ID")
			if stem == name || stem == "" {
				return nil, fmt.Errorf("%s: type name must end with ID", name)
			}
			types = append(types, identType{Name: name, Stem: stem})
		}
	}
	return types, nil
}

func isUUIDType(expr ast.Expr) bool {
	sel, ok := expr.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "UUID" {
		return false
	}
	pkg, ok := sel.X.(*ast.Ident)
	return ok && pkg.Name == "uuid"
}
